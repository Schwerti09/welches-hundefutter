async function run() {
  console.log(`🌐 Starte Meinungsnetz-Seed (${insights.length} Einträge)...`);

  // Alte Daten leeren für sauberen Neustart
  await sql`TRUNCATE community_insights RESTART IDENTITY`;
  console.log("🗑️  Alte Einträge geleert.");

  let count = 0;
  for (const row of insights) {
    await sql`
      INSERT INTO community_insights
        (platform, source_url, author, content_excerpt, sentiment,
         mentioned_brands, mentioned_topics, related_study_slugs,
         related_product_slugs, upvotes, published_at, language, verified)
      VALUES (
        ${row.platform}, ${row.source_url}, ${row.author},
        ${row.content_excerpt}, ${row.sentiment},
        ${row.mentioned_brands}, ${row.mentioned_topics},
        ${row.related_study_slugs}, ${row.related_product_slugs},
        ${row.upvotes ?? null}, ${row.published_at ?? null},
        'de', ${row.verified}
      )
    `;
    count++;
  }

  console.log(`✅ ${count} Community-Insights eingefügt.`);
  console.log("🕸️  Meinungsnetz-Daten bereit!");
}

run().catch((e) => { console.error(e); process.exit(1); });
